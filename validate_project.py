"""Independent internal consistency checks for generated project outputs.

Run from repository root: python validate_project.py
Requires CSV outputs generated by the notebook's Run All command.
"""
from pathlib import Path
import sys
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"


def load(filename, columns):
    path = DATA / filename
    if not path.is_file():
        raise FileNotFoundError(f"Missing {path}. Run notebook cells from the start and save outputs.")
    df = pd.read_csv(path)
    missing = sorted(set(columns) - set(df.columns))
    if missing:
        raise AssertionError(f"{filename} is missing columns: {missing}")
    return df


def close(value, expected, label, atol=1e-6):
    if not np.isclose(float(value), expected, atol=atol, rtol=0):
        raise AssertionError(f"{label}: found {value}, expected {expected}")
    print(f"PASS: {label}")


def verify():
    notebook = ROOT / "notebooks" / "PV_Battery_Energy_Model.ipynb"
    if not notebook.is_file():
        raise FileNotFoundError(f"Missing notebook: {notebook}")
    print("PASS: notebook exists")

    steady = load("steady_day_simulation.csv", [
        "Hour", "Demand_kWh", "PV_Generation_kWh", "PV_to_Load_kWh",
        "PV_to_Battery_kWh", "Battery_to_Load_kWh", "Grid_Import_kWh",
        "PV_Curtailed_kWh", "Battery_Start_kWh", "Battery_End_kWh",
        "Battery_SOC_pct", "Charge_Loss_kWh", "Discharge_Loss_kWh"
    ])
    if len(steady) != 24:
        raise AssertionError("steady-day simulation must have exactly 24 hours")
    print("PASS: 24 simulation intervals")

    np.testing.assert_allclose(
        steady["Demand_kWh"],
        steady["PV_to_Load_kWh"] + steady["Battery_to_Load_kWh"] + steady["Grid_Import_kWh"],
        atol=1e-8
    )
    print("PASS: hourly demand balance")
    np.testing.assert_allclose(
        steady["PV_Generation_kWh"],
        steady["PV_to_Load_kWh"] + steady["PV_to_Battery_kWh"] + steady["PV_Curtailed_kWh"],
        atol=1e-8
    )
    print("PASS: hourly PV balance")

    first_energy = float(steady["Battery_Start_kWh"].iloc[0])
    final_energy = float(steady["Battery_End_kWh"].iloc[-1])
    close(first_energy, final_energy, "periodic battery energy condition", atol=1e-8)
    if not steady["Battery_SOC_pct"].between(20 - 1e-7, 90 + 1e-7).all():
        raise AssertionError("Battery SOC outside 20%-90% range")
    print("PASS: battery SOC limits")
    total_input = (steady["PV_Generation_kWh"].sum()
                   + steady["Grid_Import_kWh"].sum() + first_energy)
    total_output = (steady["Demand_kWh"].sum() + steady["PV_Curtailed_kWh"].sum()
                    + steady["Charge_Loss_kWh"].sum()
                    + steady["Discharge_Loss_kWh"].sum() + final_energy)
    close(total_input, total_output, "whole-day energy balance", atol=1e-7)

    close(steady["Demand_kWh"].sum(), 36.7, "daily demand")
    close(steady["PV_Generation_kWh"].sum(), 27.84, "daily PV generation")
    close(steady["Grid_Import_kWh"].sum(), 9.5386, "daily PV-battery grid import")

    economics = load("techno_economic_results.csv", [
        "Scenario", "Annual_Operating_Cost_NGN", "Annual_Net_Savings_NGN", "Payback_Years"
    ])
    environmental = load("environmental_impact_results.csv", [
        "Scenario", "Annual_CO2_tonnes"
    ])
    expected = {
        "Grid Only": (2679100, 6.027975),
        "Grid + Solar PV": (1184860, 2.598435),
        "Grid + Solar PV + Battery": (751317.8, 1.56671505),
    }
    for name, (cost, co2) in expected.items():
        e = economics.loc[economics["Scenario"] == name]
        c = environmental.loc[environmental["Scenario"] == name]
        if len(e) != 1 or len(c) != 1:
            raise AssertionError(f"Missing or duplicate scenario: {name}")
        close(e["Annual_Operating_Cost_NGN"].iloc[0], cost, f"cost for {name}")
        close(c["Annual_CO2_tonnes"].iloc[0], co2, f"emissions for {name}")

    pv = load("sensitivity_pv_capacity.csv", ["PV_kWp", "Grid_kWh_day"])
    battery = load("sensitivity_battery_capacity.csv", ["Battery_kWh", "Grid_kWh_day"])
    if len(pv) != 5 or len(battery) != 5:
        raise AssertionError("Expected 5 sensitivity configurations per study")
    for value, col, df in [(5, "PV_kWp", pv), (10, "Battery_kWh", battery)]:
        found = df.loc[df[col] == value, "Grid_kWh_day"]
        if len(found) != 1:
            raise AssertionError(f"Missing sensitivity reference for {col}={value}")
        close(found.iloc[0], 9.5386, f"sensitivity reference: {col}={value}")

    figs = ["steady_day_grid_comparison.png", "annual_operating_cost_comparison.png",
            "annual_co2_emissions_comparison.png", "sensitivity_pv_capacity_energy.png",
            "sensitivity_battery_capacity_energy.png"]
    for name in figs:
        if not (ROOT / "figures" / name).is_file():
            raise FileNotFoundError(f"Missing figure: figures/{name}")
    print("PASS: primary figures present")
    print("\nALL CHECKS PASSED: Expected reference results and basic internal balances agree.")
    print("Note: This is NOT a validation against observed electrical system data.")


if __name__ == "__main__":
    try:
        verify()
    except (AssertionError, FileNotFoundError, KeyError, ValueError) as exc:
        print(f"\nVALIDATION FAILED: {exc}", file=sys.stderr)
        sys.exit(1)
